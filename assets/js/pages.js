export function renderPage(rootPath = "") {
  const target = document.getElementById("page-content");
  if (!target) return;
  const page = document.body.dataset.page || "home";
  if (page === "home") target.innerHTML = homeMarkup();
  else if (page.startsWith("service:"))
    target.innerHTML = serviceMarkup(page.split(":")[1]);
  else if (legalPages[page]) target.innerHTML = legalMarkup(legalPages[page]);
  else target.innerHTML = generalMarkup(page);
  const serviceKey = page.startsWith("service:") ? page.split(":")[1] : "";
  const title = page.startsWith("service:")
    ? offeredServiceKeys.includes(serviceKey)
      ? services[serviceKey]?.title
      : "Services"
    : legalPages[page]?.title;
  if (title) document.title = `${title} | Fanaka Noblewealth Advisory`;
  document.dispatchEvent(
    new CustomEvent("fanaka:content-ready", {
      detail: { page, root: rootPath },
    }),
  );
  target
    .querySelectorAll("[data-reveal]")
    .forEach((node) => node.classList.add("is-visible"));
  if (!target.dataset.languageListener) {
    target.dataset.languageListener = "true";
    document.addEventListener("fanaka:language", () => renderPage(rootPath));
  }
  const search = target.querySelector("[data-article-search]");
  const filter = target.querySelector("[data-article-filter]");
  const applyFilters = () =>
    target.querySelectorAll("[data-article]").forEach((article) => {
      const query = (search?.value || "").toLowerCase();
      const category = filter?.value || "all";
      article.hidden = !(
        article.textContent.toLowerCase().includes(query) &&
        (category === "all" || article.dataset.category === category)
      );
    });
  search?.addEventListener("input", applyFilters);
  filter?.addEventListener("change", applyFilters);
}
