export async function initLanguage(root = "") {
  let dictionaries = translations;
  try {
    const [en, sw] = await Promise.all(
      ["en", "sw"].map(async (lang) => {
        const response = await fetch(`${root}assets/i18n/${lang}.json`);
        return response.ok
          ? [lang, await response.json()]
          : [lang, translations[lang]];
      }),
    );
    dictionaries = {
      en: { ...translations.en, ...en[1] },
      sw: { ...translations.sw, ...sw[1] },
    };
  } catch {
    /* Embedded dictionaries keep the site usable from basic static hosts. */
  }
  const saved = localStorage.getItem("fanaka-language");
  const initial = saved === "sw" ? "sw" : "en";
  const applyLanguage = (lang) => {
    const dictionary = dictionaries[lang] || dictionaries.en;
    document.documentElement.lang = lang;
    document
      .querySelectorAll("[data-language]")
      .forEach((button) =>
        button.setAttribute(
          "aria-pressed",
          String(button.dataset.language === lang),
        ),
      );
    document.querySelectorAll("[data-i18n]").forEach((node) => {
      const value = dictionary[node.dataset.i18n];
      if (value) node.innerHTML = value;
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
      const value = dictionary[node.dataset.i18nPlaceholder];
      if (value) node.placeholder = value;
    });
    document.querySelectorAll("[data-i18n-title]").forEach((node) => {
      const value = dictionary[node.dataset.i18nTitle];
      if (value) node.title = value;
    });
    document.querySelectorAll("[data-i18n-aria]").forEach((node) => {
      const value = dictionary[node.dataset.i18nAria];
      if (value) node.setAttribute("aria-label", value);
    });
    window.FanakaLanguage = lang;
    window.FanakaTranslate = (key) => dictionary[key] || key;
    localStorage.setItem("fanaka-language", lang);
    document.dispatchEvent(
      new CustomEvent("fanaka:language", { detail: { lang } }),
    );
  };
  applyLanguage(initial);
  document.addEventListener("click", (event) => {
    const button = event.target.closest("[data-language]");
    if (button) applyLanguage(button.dataset.language);
  });
}
